/** A third-party package that ships with MovIQ in production. */
export interface ShippedPackage {
  readonly name: string;
  readonly version: string;
  readonly license: string | undefined;
}

/** Permissive licences only: none of them asks MovIQ to change its own licence. */
const ALLOWED_LICENSES: ReadonlySet<string> = new Set([
  '0BSD',
  'Apache-2.0',
  'BlueOak-1.0.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'CC0-1.0',
  'ISC',
  'MIT',
  // Fonts: the SIL Open Font License covers only the font files, which ship unchanged.
  'OFL-1.1',
]);

/** Exceptions that only add permissions to the licence they follow. */
const ALLOWED_EXCEPTIONS: ReadonlySet<string> = new Set(['LLVM-exception']);

/**
 * True when an SPDX expression can be satisfied with allowed licences. `AND` binds tighter than
 * `OR`, parentheses group, and `WITH` attaches an exception. Anything malformed is refused.
 */
export function isAllowedLicense(expression: string | undefined): boolean {
  if (expression === undefined) return false;
  const tokens = expression
    .replaceAll('(', ' ( ')
    .replaceAll(')', ' ) ')
    .split(/\s+/)
    .filter((token) => token !== '');
  if (tokens.length === 0) return false;
  const cursor = { tokens, at: 0 };
  try {
    const allowed = parseOr(cursor);
    return cursor.at === tokens.length && allowed;
  } catch {
    return false;
  }
}

interface Cursor {
  readonly tokens: readonly string[];
  at: number;
}

function parseOr(cursor: Cursor): boolean {
  let allowed = parseAnd(cursor);
  while (cursor.tokens[cursor.at] === 'OR') {
    cursor.at += 1;
    allowed = parseAnd(cursor) || allowed;
  }
  return allowed;
}

function parseAnd(cursor: Cursor): boolean {
  let allowed = parseTerm(cursor);
  while (cursor.tokens[cursor.at] === 'AND') {
    cursor.at += 1;
    allowed = parseTerm(cursor) && allowed;
  }
  return allowed;
}

function parseTerm(cursor: Cursor): boolean {
  const token = take(cursor);
  if (token === '(') {
    const allowed = parseOr(cursor);
    if (take(cursor) !== ')') throw new SyntaxError('unclosed parenthesis');
    return allowed;
  }
  if (token === ')' || token === 'AND' || token === 'OR' || token === 'WITH') {
    throw new SyntaxError(`unexpected ${token}`);
  }
  if (cursor.tokens[cursor.at] !== 'WITH') return ALLOWED_LICENSES.has(token);
  cursor.at += 1;
  return ALLOWED_LICENSES.has(token) && ALLOWED_EXCEPTIONS.has(take(cursor));
}

function take(cursor: Cursor): string {
  const token = cursor.tokens[cursor.at];
  if (token === undefined) throw new SyntaxError('unexpected end');
  cursor.at += 1;
  return token;
}

/** A file copied into the repository from another project, shipped under its own licence. */
export interface VendoredFile {
  readonly path: string;
  readonly origin: string;
  readonly license: string;
}

export const VENDORED_FILES: readonly VendoredFile[] = [
  {
    path: 'apps/server/vendor/gtfs-realtime.proto',
    origin: 'https://github.com/google/transit (GTFS Realtime specification)',
    license: 'Apache-2.0',
  },
];

interface LockEntry {
  readonly version?: string;
  readonly license?: string;
  readonly dev?: boolean;
  /** Optional dependency of production code that is also a dev dependency: it ships. */
  readonly devOptional?: boolean;
  readonly link?: boolean;
}

/**
 * Production packages from `package-lock.json`. The lockfile lists the native builds for every
 * platform, so the result is the same on every machine.
 */
export function shippedPackages(lock: {
  readonly packages: Readonly<Record<string, LockEntry>>;
}): readonly ShippedPackage[] {
  const shipped = new Map<string, ShippedPackage>();
  for (const [path, entry] of Object.entries(lock.packages)) {
    if (!path.includes('node_modules/') || entry.link === true) continue;
    // `devOptional` packages are optional dependencies of production code: they ship too.
    if (entry.dev === true || entry.version === undefined) continue;
    const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
    const pkg = { name, version: entry.version, license: entry.license };
    shipped.set(`${name}@${entry.version}`, pkg);
  }
  return [...shipped.values()].sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
}

export function renderNotices(
  packages: readonly ShippedPackage[],
  vendored: readonly VendoredFile[] = VENDORED_FILES,
): string {
  const rows = packages.map(
    (pkg) => `| ${pkg.name} | ${pkg.version} | ${pkg.license ?? 'unknown'} |`,
  );
  const vendoredRows = vendored.map(
    (file) => `| \`${file.path}\` | ${file.origin} | ${file.license} |`,
  );
  return [
    '# Third-party notices',
    '',
    'MovIQ ships with these open-source packages. This file is generated by `npm run notices`',
    'from `package-lock.json`, and `npm run verify` fails if it is out of date.',
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
    ...rows,
    '',
    '## Files copied from other projects',
    '',
    '| File | Origin | Licence |',
    '| --- | --- | --- |',
    ...vendoredRows,
    '',
  ].join('\n');
}
